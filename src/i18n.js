export function detectLang(request) {
  const country = (
    request.cf?.country || request.headers.get('CF-IPCountry') || ''
  ).toString().trim().toUpperCase();
  const acceptLang = (request.headers.get('Accept-Language') || '').toLowerCase();

  if (['CN', 'TW', 'HK', 'MO'].includes(country)) return 'zh';

  const zhPos = acceptLang.indexOf('zh');
  const enPos = acceptLang.indexOf('en');
  if (zhPos !== -1 && (enPos === -1 || zhPos < enPos)) return 'zh';
  return 'en';
}

// Shared language resolution for all server-rendered pages:
// ?lang= param (highest priority) > osh_lang cookie > request detection.
export function resolveLang(request) {
  const url = new URL(request.url);
  const param = url.searchParams.get('lang');
  if (param === 'zh' || param === 'en') return param;

  const cookies = request.headers.get('Cookie') || '';
  const match = cookies.match(/(?:^|;\s*)osh_lang=(zh|en)/);
  if (match) return match[1];

  return detectLang(request);
}

